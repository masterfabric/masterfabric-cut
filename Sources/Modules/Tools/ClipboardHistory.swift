// MARK: - Model

struct ClipboardItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, image }
    var id = UUID()
    var date = Date()
    var kind: Kind
    var text: String?
    /// PNG bytes for images (kept in memory; written to disk only when persistence is on).
    var imageData: Data?
    var pixelSize: CGSize?
    var sourceApp: String?

    enum CodingKeys: String, CodingKey { case id, date, kind, text, pixelSize, sourceApp }

    var preview: String {
        switch kind {
        case .text: return (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        case .image:
            if let s = pixelSize { return "Image \(Int(s.width)) × \(Int(s.height))" }
            return "Image"
        }
    }

    var image: NSImage? { imageData.flatMap { NSImage(data: $0) } }

    func matches(_ query: String) -> Bool {
        guard !query.isEmpty else { return true }
        return preview.localizedCaseInsensitiveContains(query) || (sourceApp ?? "").localizedCaseInsensitiveContains(query)
    }
}

/// Watches the general pasteboard and keeps the last 50 text / image items.
/// Password managers and other apps that mark items as concealed, transient or auto-generated are skipped
/// (nspasteboard.org conventions). History stays on this Mac; disk persistence is opt-in.
@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    static let maxItems = 50

    @Published private(set) var items: [ClipboardItem] = []
    @Published private(set) var isRunning = false

    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private let pb = NSPasteboard.general

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "net.antelle.keeweb",
    ]

    private var directory: URL {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return base.appendingPathComponent("MasterFabric Cut/Clipboard", isDirectory: true)
    }

    /// Start/stop the watcher and load/delete stored history to match Settings.
    func applySettings() {
        let s = AppSettings.shared
        if s.clipboardHistoryEnabled { start() } else { stop() }
        if s.clipboardPersist {
            if items.isEmpty { load() } else { save() }
        } else {
            try? FileManager.default.removeItem(at: directory)
        }
    }

    func start() {
        guard timer == nil else { return }
        if AppSettings.shared.clipboardPersist && items.isEmpty { load() }
        lastChange = pb.changeCount
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
        isRunning = true
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        isRunning = false
    }

    private func poll() {
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(ClipboardItem(kind: .text, text: s, sourceApp: app))
        } else if let img = NSImage(pasteboard: pb), let png = img.pngData() {
            let rep = img.representations.first
            let size = rep.map { CGSize(width: $0.pixelsWide, height: $0.pixelsHigh) } ?? img.size
            add(ClipboardItem(kind: .image, imageData: png, pixelSize: size, sourceApp: app))
        }
    }

    private func add(_ item: ClipboardItem) {
        if let i = items.firstIndex(where: { same($0, item) }) { items.remove(at: i) }
        items.insert(item, at: 0)
        if items.count > Self.maxItems { items.removeLast(items.count - Self.maxItems) }
        save()
    }

    private func same(_ a: ClipboardItem, _ b: ClipboardItem) -> Bool {
        a.kind == b.kind && (a.kind == .text ? a.text == b.text : a.imageData == b.imageData)
    }

    /// Put an item back on the clipboard (moves it to the top) without recording it twice.
    func copyBack(_ item: ClipboardItem) {
        pb.clearContents()
        switch item.kind {
        case .text: pb.setString(item.text ?? "", forType: .string)
        case .image: if let img = item.image { pb.writeObjects([img]) }
        }
        lastChange = pb.changeCount
        if let i = items.firstIndex(of: item) {
            var moved = items.remove(at: i)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    func delete(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    func clear() {
        items.removeAll()
        try? FileManager.default.removeItem(at: directory)
        Toast.show("Clipboard history cleared", symbol: "trash.fill", tint: .orange)
    }

    #if DEBUG
    /// Demo content for snapshots so a real clipboard never ends up in screenshots.
    func loadDemoItems() {
        let samples = ["https://masterfabric.co/cut", "Toplantı notları: Perşembe 14:00, ürün demosu",
                       "{\"name\": \"MasterFabric Cut\", \"version\": \"0.1.3\"}", "git checkout -b feat/general-tools",
                       "#4F7DF3", "Merhaba! Ekran görüntüsü ekte."]
        let apps = ["Safari", "Notes", "Xcode", "Terminal", "Figma", "Mail"]
        items = zip(samples, apps).enumerated().map { i, p in
            ClipboardItem(date: Date().addingTimeInterval(Double(-i * 340)), kind: .text, text: p.0, sourceApp: p.1)
        }
        let img = NSImage(size: NSSize(width: 64, height: 40), flipped: false) { r in
            NSGradient(colors: [.systemBlue, .systemPurple])?.draw(in: r, angle: 30); return true
        }
        items.insert(ClipboardItem(date: Date().addingTimeInterval(-90), kind: .image, imageData: img.pngData(),
                                   pixelSize: CGSize(width: 1280, height: 800), sourceApp: "MasterFabric Cut"), at: 2)
    }
    #endif

    // MARK: Persistence (opt-in, local only)

    private func save() {
        guard AppSettings.shared.clipboardPersist else { return }
        let fm = FileManager.default
        try? fm.createDirectory(at: directory, withIntermediateDirectories: true)
        if let data = try? JSONEncoder().encode(items) {
            try? data.write(to: directory.appendingPathComponent("index.json"), options: .atomic)
        }
        let keep = Set(items.filter { $0.kind == .image }.map { "\($0.id.uuidString).png" })
        for item in items where item.kind == .image {
            let url = directory.appendingPathComponent("\(item.id.uuidString).png")
            if !fm.fileExists(atPath: url.path) { try? item.imageData?.write(to: url) }
        }
        for name in (try? fm.contentsOfDirectory(atPath: directory.path)) ?? [] where name.hasSuffix(".png") && !keep.contains(name) {
            try? fm.removeItem(at: directory.appendingPathComponent(name))
        }
    }

    private func load() {
        guard let data = try? Data(contentsOf: directory.appendingPathComponent("index.json")),
              var stored = try? JSONDecoder().decode([ClipboardItem].self, from: data) else { return }
        for i in stored.indices where stored[i].kind == .image {
            stored[i].imageData = try? Data(contentsOf: directory.appendingPathComponent("\(stored[i].id.uuidString).png"))
        }
        items = stored.filter { $0.kind == .text || $0.imageData != nil }
    }
}

extension NSImage {
    func pngData() -> Data? {
        guard let tiff = tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}

// MARK: - Picker panel

private final class ClipboardPickerPanel: NSPanel {
    override var canBecomeKey: Bool { true }
    override var canBecomeMain: Bool { false }
}

@MainActor
final class ClipboardPickerModel: ObservableObject {
    @Published var query = "" { didSet { selection = 0 } }
    @Published var selection = 0
    var results: [ClipboardItem] { ClipboardHistory.shared.items.filter { $0.matches(query) } }
}

/// Searchable list shown with ⌃⇧⌘V. ↩ pastes into the previous app (needs Accessibility, otherwise it copies),
/// ⌥↩ copies only, ⌘1…⌘9 pastes that row, ⌘⌫ removes the item, Esc closes.
@MainActor
final class ClipboardPicker {
    static let shared = ClipboardPicker()
    private var panel: NSPanel?
    private var monitor: Any?
    private var previousApp: NSRunningApplication?
    private let model = ClipboardPickerModel()

    var isVisible: Bool { panel?.isVisible == true }

    func toggle() { isVisible ? close() : show() }

    func show() {
        if !AppSettings.shared.clipboardHistoryEnabled {
            Toast.show("Clipboard history is off — turn it on in Settings › Tools", symbol: "clipboard", tint: .orange, duration: 2.4)
        }
        let front = NSWorkspace.shared.frontmostApplication
        if front?.bundleIdentifier != Bundle.main.bundleIdentifier { previousApp = front }
        model.query = ""
        model.selection = 0
        let p = panel ?? makePanel()
        panel = p
        let screen = NSScreen.underMouse ?? NSScreen.main
        if let vf = screen?.visibleFrame {
            p.setFrameOrigin(NSPoint(x: vf.midX - p.frame.width / 2, y: vf.midY - p.frame.height / 2 + vf.height * 0.12))
        }
        NSApp.activate(ignoringOtherApps: true)
        p.makeKeyAndOrderFront(nil)
        installMonitor()
    }

    func close() {
        if let m = monitor { NSEvent.removeMonitor(m); monitor = nil }
        panel?.orderOut(nil)
    }

    private func makePanel() -> NSPanel {
        let p = ClipboardPickerPanel(contentRect: NSRect(x: 0, y: 0, width: 520, height: 440),
                                     styleMask: [.borderless, .nonactivatingPanel, .fullSizeContentView], backing: .buffered, defer: false)
        p.isFloatingPanel = true
        p.level = .floating
        p.backgroundColor = .clear
        p.isOpaque = false
        p.hasShadow = true
        p.hidesOnDeactivate = false
        p.isReleasedWhenClosed = false
        p.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
        p.contentView = NSHostingView(rootView: ClipboardPickerView(model: model, history: .shared,
                                                                    choose: { [weak self] item, paste in self?.choose(item, paste: paste) },
                                                                    close: { [weak self] in self?.close() }))
        return p
    }

    private func installMonitor() {
        guard monitor == nil else { return }
        monitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] e in
            guard let self, self.isVisible, e.window === self.panel else { return e }
            let results = self.model.results
            switch Int(e.keyCode) {
            case kVK_Escape: self.close(); return nil
            case kVK_DownArrow: self.model.selection = min(self.model.selection + 1, max(results.count - 1, 0)); return nil
            case kVK_UpArrow: self.model.selection = max(self.model.selection - 1, 0); return nil
            case kVK_Return, kVK_ANSI_KeypadEnter:
                if results.indices.contains(self.model.selection) {
                    self.choose(results[self.model.selection], paste: !e.modifierFlags.contains(.option))
                }
                return nil
            case kVK_Delete where e.modifierFlags.contains(.command):
                if results.indices.contains(self.model.selection) {
                    ClipboardHistory.shared.delete(results[self.model.selection])
                    self.model.selection = min(self.model.selection, max(self.model.results.count - 1, 0))
                }
                return nil
            default:
                // ⌘1…⌘9 pastes the n-th visible item.
                if e.modifierFlags.contains(.command), let c = e.charactersIgnoringModifiers, let n = Int(c), (1...9).contains(n),
                   results.indices.contains(n - 1) {
                    self.choose(results[n - 1], paste: true); return nil
                }
                return e
            }
        }
    }

    private func choose(_ item: ClipboardItem, paste: Bool) {
        ClipboardHistory.shared.copyBack(item)
        close()
        let target = previousApp
        guard paste else { Toast.show("Copied", symbol: "doc.on.clipboard.fill", tint: .blue); return }
        guard AXIsProcessTrusted() else {
            Toast.show("Copied — press ⌘V to paste (Accessibility permission enables auto-paste)", symbol: "doc.on.clipboard.fill", tint: .blue, duration: 2.6)
            return
        }
        target?.activate()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.18) {
            let src = CGEventSource(stateID: .combinedSessionState)
            let down = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true)
            let up = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false)
            down?.flags = .maskCommand
            up?.flags = .maskCommand
            down?.post(tap: .cghidEventTap)
            up?.post(tap: .cghidEventTap)
        }
    }
}

struct ClipboardPickerView: View {
    @ObservedObject var model: ClipboardPickerModel
    @ObservedObject var history: ClipboardHistory
    let choose: (ClipboardItem, Bool) -> Void
    let close: () -> Void
    @FocusState private var searchFocused: Bool

    var body: some View {
        let results = model.results
        VStack(spacing: 0) {
            HStack(spacing: 8) {
                Image(systemName: "magnifyingglass").foregroundStyle(.secondary)
                TextField("Search clipboard history", text: $model.query)
                    .textFieldStyle(.plain).font(.system(size: 15))
                    .focused($searchFocused)
                Text("\(history.items.count)/\(ClipboardHistory.maxItems)")
                    .font(.system(size: 10, weight: .semibold, design: .rounded)).foregroundStyle(.tertiary)
            }
            .padding(.horizontal, 14).padding(.vertical, 12)
            Divider()
            if results.isEmpty {
                VStack(spacing: 8) {
                    Image(systemName: "clipboard").font(.system(size: 28)).foregroundStyle(.tertiary)
                    Text(history.items.isEmpty ? "Nothing copied yet" : "No matches").foregroundStyle(.secondary)
                }
                .frame(maxWidth: .infinity, maxHeight: .infinity)
            } else {
                ScrollViewReader { proxy in
                    ScrollView {
                        LazyVStack(spacing: 2) {
                            ForEach(Array(results.enumerated()), id: \.element.id) { i, item in
                                row(item, index: i, selected: i == model.selection)
                                    .id(item.id)
                                    .onTapGesture { choose(item, true) }
                            }
                        }
                        .padding(6)
                    }
                    .onChange(of: model.selection) { _, s in
                        if results.indices.contains(s) { proxy.scrollTo(results[s].id) }
                    }
                }
            }
            Divider()
            HStack(spacing: 14) {
                hint("↩", "Paste"); hint("⌥↩", "Copy"); hint("⌘⌫", "Remove"); hint("esc", "Close")
                Spacer()
                Button("Clear All") { history.clear() }.buttonStyle(.borderless).font(.system(size: 11))
                    .disabled(history.items.isEmpty)
            }
            .padding(.horizontal, 14).padding(.vertical, 8)
        }
        .frame(width: 520, height: 440)
        .background(.regularMaterial, in: RoundedRectangle(cornerRadius: 14, style: .continuous))
        .overlay(RoundedRectangle(cornerRadius: 14, style: .continuous).strokeBorder(.white.opacity(0.12)))
        .onAppear { searchFocused = true }
    }

    private func row(_ item: ClipboardItem, index: Int, selected: Bool) -> some View {
        HStack(spacing: 10) {
            Group {
                if item.kind == .image, let img = item.image {
                    Image(nsImage: img).resizable().aspectRatio(contentMode: .fill)
                } else {
                    Image(systemName: "text.alignleft").foregroundStyle(.secondary)
                }
            }
            .frame(width: 34, height: 26)
            .background(.quaternary.opacity(0.5), in: RoundedRectangle(cornerRadius: 5))
            .clipShape(RoundedRectangle(cornerRadius: 5))
            VStack(alignment: .leading, spacing: 2) {
                Text(item.preview.replacingOccurrences(of: "\n", with: " ⏎ "))
                    .lineLimit(1).truncationMode(.tail).font(.system(size: 13))
                Text([item.sourceApp, item.date.formatted(.relative(presentation: .named))].compactMap { $0 }.joined(separator: " · "))
                    .font(.system(size: 10)).foregroundStyle(.secondary)
            }
            Spacer()
            if index < 9 { Text("⌘\(index + 1)").font(.system(size: 10, weight: .semibold, design: .rounded)).foregroundStyle(.tertiary) }
        }
        .padding(.horizontal, 8).padding(.vertical, 6)
        .background(selected ? Color.accentColor.opacity(0.22) : .clear, in: RoundedRectangle(cornerRadius: 8, style: .continuous))
        .contentShape(Rectangle())
    }

    private func hint(_ key: String, _ label: String) -> some View {
        HStack(spacing: 4) {
            Text(key).font(.system(size: 10, weight: .semibold, design: .rounded))
                .padding(.horizontal, 5).padding(.vertical, 1)
                .background(.quaternary, in: RoundedRectangle(cornerRadius: 4))
            Text(label).font(.system(size: 10)).foregroundStyle(.secondary)
        }
    }
}
